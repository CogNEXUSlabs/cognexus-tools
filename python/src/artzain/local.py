def render_compose(manifest: dict[str, Any]) -> str:
    refs = image_refs(manifest)
    template = resources.files("artzain").joinpath(_COMPOSE_TEMPLATE).read_text(
        encoding="utf-8")
    return (template
            .replace("__CORE_IMAGE__", refs["cognexus-core"])
            .replace("__FRONTEND_IMAGE__", refs["cognexus-frontend"]))


def _render_env(existing: dict[str, str],
                ui_port_choice: int | None) -> tuple[str, bool]:
    """The .env content: keep existing values, generate only the missing.

    Returns ``(text, changed)``. ``ui_port_choice`` overrides the stored
    port when explicitly given (the ``--port`` flag); otherwise the stored
    value — or the default — stands.
    """
    values = dict(existing)
    changed = False
    for key, entropy in _ENV_SECRET_KEYS:
        if not values.get(key):
            values[key] = _secrets.token_urlsafe(entropy)
            changed = True
    if ui_port_choice is not None:
        if values.get("COGNEXUS_UI_PORT") != str(ui_port_choice):
            changed = True
        values["COGNEXUS_UI_PORT"] = str(ui_port_choice)
    elif not values.get("COGNEXUS_UI_PORT"):
        values["COGNEXUS_UI_PORT"] = str(_UI_PORT_DEFAULT)
        changed = True
    managed = [k for k, _ in _ENV_SECRET_KEYS] + ["COGNEXUS_UI_PORT"]
    lines = [f"{key}={values[key]}" for key in managed]
    # Preserve any extra keys the operator added (they own this file too).
    extras = [f"{k}={v}" for k, v in values.items() if k not in managed]
    return _ENV_HEADER + "\n".join(lines + extras) + "\n", changed


def read_env() -> dict[str, str]:
    env_file = _env_path()
    values: dict[str, str] = {}
    if not env_file.is_file():
        return values
    for line in env_file.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        val = val.strip()
        # Hand-edited files often quote values dotenv-style; compose strips
        # quotes, so this parser must too or the two disagree about the port.
        if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
            val = val[1:-1]
        values[key.strip()] = val
    return values


def ui_port() -> int:
    try:
        return int(read_env().get("COGNEXUS_UI_PORT") or _UI_PORT_DEFAULT)
    except ValueError:
        return _UI_PORT_DEFAULT


def base_url() -> str:
    return f"http://localhost:{ui_port()}"


def ensure_workspace(manifest: dict[str, Any],
                     ui_port_choice: int | None = None) -> dict[str, Any]:
    """Write compose.yaml + pins.json; create or REPAIR the .env.

    Existing secret values are never overwritten; missing ones are filled
    in, so a hand-created .env (or one from an interrupted run) cannot
    leave the stack without a Postgres password.
    """
    ws = workspace_dir()
    ws.mkdir(parents=True, exist_ok=True)
    backups_dir().mkdir(parents=True, exist_ok=True)

    existing = read_env()
    env_text, env_changed = _render_env(existing, ui_port_choice)
    if env_changed or not _env_path().is_file():
        _write_atomic(_env_path(), env_text)
        try:  # POSIX only; harmless elsewhere
            _env_path().chmod(0o600)
        except OSError:
            pass

    _write_atomic(_compose_path(), render_compose(manifest))
    pins = applied_pins() or {}
    pins.update({
        "version": manifest.get("version"),
        "registry": manifest.get("registry"),
        "images": manifest.get("images"),
        "source_commit": manifest.get("source_commit"),
        "applied_at": datetime.now(timezone.utc).isoformat(),
    })
    _write_atomic(_pins_path(), json.dumps(pins, indent=2, sort_keys=True))
    return {"workspace": str(ws), "env_created": not existing,
            "env_repaired": bool(existing) and env_changed,
            "version": pins["version"]}


def applied_pins() -> dict[str, Any] | None:
    try:
        return json.loads(_pins_path().read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _remember_install_id(payload: dict[str, Any]) -> None:
    """Persist the install id so ``--purge`` can demand it even when the
    stack is stopped — the normal state in which purges happen."""
    install_id = str(payload.get("install_id") or "").strip()
    pins = applied_pins()
    if not install_id or not pins or pins.get("install_id") == install_id:
        return
    pins["install_id"] = install_id
    _write_atomic(_pins_path(), json.dumps(pins, indent=2, sort_keys=True))


