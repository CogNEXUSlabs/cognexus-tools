"""``artzain local`` — the self-serve in-boundary installer (WS-B).

One command stands the engine up beside a local dashboard:

* ``up``       render the workspace, pull digest-pinned images, wait healthy,
               hand off to the browser's first-run page.
* ``doctor``   preflight; every failure prints one remedial sentence.
* ``status``   health, trial standing, and whether an update is available.
* ``upgrade``  dump the database FIRST, then re-pin to the channel's digests.
* ``down``     stop (data stays); ``--purge`` destroys volumes after an
               explicit confirmation naming the install.
* ``reset``    the dirty-reinstall path: the same confirmation, then purge.
* ``create-admin``  headless first-run (the /welcome page without a browser).

The workspace is ``~/.cognexus`` (override: ``COGNEXUS_LOCAL_HOME``):
``compose.yaml`` is rewritten on every pin change and never hand-edited;
``.env`` is generated with real random secrets and repaired in place if keys
are missing — existing values are never overwritten; ``pins.json`` records
which release is applied (and the install id, so ``--purge`` can name it
even with the stack stopped); ``backups/`` holds the pre-upgrade dumps.

Digests, not tags: the stable-channel manifest (WS-A) names an image digest
per repository — the same digest the release's cosign signature covers — and
the rendered compose file bakes those digests in. The postgres base image is
digest-pinned in the template for the same reason. Nothing here pulls a
bare tag.
"""

