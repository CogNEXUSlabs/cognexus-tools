DEFAULT_MANIFEST_URL = "https://cognexuslabs.ai/downloads/stable.json"
_COMPOSE_TEMPLATE = "_local_compose.yaml.tpl"
_PROJECT = "cognexus"
_UI_PORT_DEFAULT = 8080
_HEALTH_TIMEOUT_S = 240
_MIN_DUMP_BYTES = 1024  # matches the compose backup floor in the engine repo
_MIN_FREE_BYTES = 2 * 1024**3

_REQUIRED_IMAGES = ("cognexus-core", "cognexus-frontend")
_DIGEST_RE = re.compile(r"^sha256:[0-9a-f]{64}$")

#: Secrets the workspace .env must carry. Generation is per-key so a
#: hand-created file (e.g. someone editing the port before first run) is
#: repaired in place rather than silently left without a Postgres password —
#: the all-or-nothing version of this bricked exactly that path.
_ENV_SECRET_KEYS = (
    ("POSTGRES_PASSWORD", 24),
    ("JWT_SECRET_KEY", 48),
    ("COGNEXUS_API_KEY_PEPPER", 32),
    ("COGNEXUS_BOOTSTRAP_TOKEN", 24),
)

_ENV_HEADER = (
    "# Generated by `artzain local up`. Secrets are per-install; keep the\n"
    "# file. Deleting it (or `artzain local reset`) strands the install's\n"
    "# JWTs and API-key hashes.\n"
)


class LocalError(RuntimeError):
    """A failure with its remedy in the message — print, don't traceback."""


# ---------------------------------------------------------------------------
# Workspace
# ---------------------------------------------------------------------------


def workspace_dir() -> Path:
    override = (os.environ.get("COGNEXUS_LOCAL_HOME") or "").strip()
    return Path(override) if override else Path.home() / ".cognexus"


def _compose_path() -> Path:
    return workspace_dir() / "compose.yaml"


def _env_path() -> Path:
    return workspace_dir() / ".env"


def _pins_path() -> Path:
    return workspace_dir() / "pins.json"


def backups_dir() -> Path:
    return workspace_dir() / "backups"


def _write_atomic(path: Path, text: str) -> None:
    """Never hand a half-written file to a concurrent reader (compose runs
    ``-f`` on these)."""
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


@contextmanager
def _workspace_lock():
    """One mutating ``artzain local`` command at a time.

    Two concurrent ``up``s each generating secrets can initialise the
    Postgres volume with one password while ``.env`` keeps the other — an
    install nothing short of ``--purge`` recovers. O_EXCL is the portable
    atomic primitive; the lock file names its holder for the stale case.
    """
    workspace_dir().mkdir(parents=True, exist_ok=True)
    lock = workspace_dir() / ".lock"
    try:
        fd = os.open(str(lock), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        raise LocalError(
            f"Another `artzain local` command appears to be running (lock: "
            f"{lock}). If that is wrong — e.g. a previous run was killed — "
            "delete the lock file and retry.") from None
    try:
        os.write(fd, f"pid={os.getpid()}\n".encode())
        os.close(fd)
        yield
    finally:
        try:
            lock.unlink()
        except OSError:
            pass


