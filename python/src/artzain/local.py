def run_doctor(port: int | None = None, out=None) -> bool:
    out = out or sys.stdout
    ok_all = True
    for name, ok, remedy in doctor_checks(port):
        mark = "ok " if ok else "FAIL"
        print(f"  [{mark}] {name}", file=out)
        if not ok:
            print(f"        -> {remedy}", file=out)
            ok_all = False
    return ok_all


def run_up(manifest_src: str | None, open_browser: bool = True,
           port: int | None = None, out=None) -> None:
    out = out or sys.stdout
    with _workspace_lock():
        print("Preflight:", file=out)
        if not run_doctor(port=port, out=out):
            raise LocalError("Fix the checks above and re-run "
                             "`artzain local up`.")

        source = manifest_source(manifest_src)
        print(f"Channel manifest: {source}", file=out)
        manifest = load_manifest(source)
        state = ensure_workspace(manifest, ui_port_choice=port)
        note = (", secrets generated" if state["env_created"]
                else ", .env repaired" if state["env_repaired"] else "")
        print(f"Workspace: {state['workspace']} "
              f"(release {state['version']}{note})", file=out)

        print("Starting the stack (first run pulls the images)...", file=out)
        _compose(["up", "-d", "--remove-orphans"])
        payload = wait_healthy(log=lambda s: print(f"  {s}", file=out))
        _remember_install_id(payload)
        print(f"Engine healthy - profile={payload.get('profile')}, "
              f"install {payload.get('install_id') or 'pending'}", file=out)

    url, note = first_run_plan()
    print(f"\nFirst run: open {url}", file=out)
    print(f"  {note}", file=out)
    if open_browser:
        import webbrowser

        webbrowser.open(url)
    print("\n  status : artzain local status\n  stop   : artzain local down",
          file=out)


def run_status(manifest_src: str | None, out=None) -> None:
    out = out or sys.stdout
    pins = applied_pins()
    print(f"Workspace : {workspace_dir()}", file=out)
    print(f"Applied   : {pins.get('version') if pins else '(never installed)'}",
          file=out)
    payload = fetch_health()
    if not payload:
        print(f"Engine    : not reachable at {base_url()} — "
              "`artzain local up` starts it.", file=out)
    else:
        print(f"Engine    : {payload.get('status')} "
              f"(profile={payload.get('profile')})", file=out)
        trial = payload.get("trial") or {}
        if trial.get("applies"):
            if trial.get("expired"):
                print("Trial     : EXPIRED — new connectors/agents/keys are "
                      "paused; decisions keep sealing. Import a licence "
                      "certificate: artzain local activate <cert.json> "
                      "(it can sign you in with your dashboard email — no "
                      "API key needed).", file=out)
            else:
                print(f"Trial     : {trial.get('days_remaining')} day(s) "
                      "remaining", file=out)
        print(f"Dashboard : {base_url()}/dashboard.html", file=out)
    if pins:
        try:
            manifest = load_manifest(manifest_source(manifest_src))
            if manifest.get("version") != pins.get("version"):
                print(f"Update    : {manifest.get('version')} is available — "
                      "`artzain local upgrade`.", file=out)
            else:
                print("Update    : up to date with the stable channel.",
                      file=out)
        except LocalError:
            print("Update    : channel manifest unreachable (offline is "
                  "fine — check again later).", file=out)


def _predump(out=None) -> Path:
    """Dump the database BEFORE anything changes; refuse to proceed without.

    Binary end to end: pg_dump's bytes stream straight into the gzip file.
    A text-mode capture decoded with the locale codec (cp1252 on Windows)
    either crashed on the first emoji or silently mojibake'd the one
    artifact this function exists to protect — and buffered the whole dump
    in RAM besides.
    """
    out = out or sys.stdout
    backups_dir().mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    target = backups_dir() / f"pre-upgrade-{stamp}.sql.gz"
    cmd = _compose_cmd(["exec", "-T", "postgres", "pg_dump", "-U", "cognexus",
                        "-d", "cognexus"])
    written = 0
    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE)
        with gzip.open(target, "wb") as fh:
            assert proc.stdout is not None
            while True:
                chunk = proc.stdout.read(256 * 1024)
                if not chunk:
                    break
                fh.write(chunk)
                written += len(chunk)
        stderr_tail = b""
        if proc.stderr is not None:
            stderr_tail = proc.stderr.read()[-500:]
        returncode = proc.wait(timeout=1800)
    except FileNotFoundError as exc:
        raise LocalError("docker is not installed — run `artzain local "
                         "doctor` for the fix.") from exc
    except (OSError, subprocess.TimeoutExpired) as exc:
        try:
            target.unlink()
        except OSError:
            pass
        raise LocalError(f"Pre-upgrade database dump failed ({exc}) — "
                         "refusing to upgrade without one.") from exc
    if returncode != 0 or written < _MIN_DUMP_BYTES:
        try:
            target.unlink()
        except OSError:
            pass
        detail = stderr_tail.decode("utf-8", errors="replace").strip()
        raise LocalError(
            "Pre-upgrade database dump failed — refusing to upgrade without "
            "one. Is the stack running? (`artzain local up` first, then "
            f"retry.){' Details: ' + detail if detail else ''}")
    print(f"Backup: {target} ({written} bytes uncompressed)", file=out)
    return target


def run_upgrade(manifest_src: str | None, out=None) -> None:
    out = out or sys.stdout
    with _workspace_lock():
        pins = applied_pins()
        if not pins:
            raise LocalError("Nothing installed yet — run `artzain local up`.")
        manifest = load_manifest(manifest_source(manifest_src))
        if manifest.get("version") == pins.get("version"):
            print(f"Already on {pins.get('version')} — nothing to do.",
                  file=out)
            return
        print(f"Upgrading {pins.get('version')} -> {manifest.get('version')}",
              file=out)
        _predump(out=out)
        ensure_workspace(manifest)
        _compose(["up", "-d", "--remove-orphans"])
        payload = wait_healthy(log=lambda s: print(f"  {s}", file=out))
        _remember_install_id(payload)
    print(f"Upgraded — engine {payload.get('status')} on "
          f"{manifest.get('version')}. Schema migrates itself on boot; the "
          "pre-upgrade dump is in backups/ if anything looks wrong.", file=out)


def run_down(purge: bool, confirm: Callable[[str], str] = input,
             out=None) -> None:
    out = out or sys.stdout
    if not _compose_path().is_file():
        print("Nothing installed — no workspace at "
              f"{workspace_dir()}.", file=out)
        return
    with _workspace_lock():
        if not purge:
            _compose(["down"])
            print("Stopped. Data volumes kept — `artzain local up` resumes "
                  "where you left off.", file=out)
            return

        # The install id was persisted at up-time precisely so this guard
        # still names THIS install when the stack is stopped.
        pins = applied_pins() or {}
        install_id = (str(pins.get("install_id") or "").strip()
                      or str((fetch_health() or {}).get("install_id") or "").strip())
        expected = install_id or "destroy-cognexus"
        print("--purge DESTROYS the database volume AND the Ed25519 audit "
              "signing keys, which are unrecoverable (manual §2.7).", file=out)
        print("Export evidence first if you need it: artzain audit export.",
              file=out)
        typed = confirm(f"Type '{expected}' to confirm: ").strip()
        if typed != expected:
            print("Not confirmed — nothing was destroyed.", file=out)
            return
        _compose(["down", "--volumes"])
        for stale in (_compose_path(), _pins_path(), _env_path()):
            try:
                stale.unlink()
            except OSError:
                pass
        print(f"Destroyed. Backups (if any) remain in {backups_dir()}.",
              file=out)


def run_create_admin(email: str, password: str, out=None) -> None:
    out = out or sys.stdout
    token = read_env().get("COGNEXUS_BOOTSTRAP_TOKEN")
    if not token:
        raise LocalError("No bootstrap token in the workspace .env — run "
                         "`artzain local up` first.")
    status, payload = _api_post("/api/auth/bootstrap-admin", {
        "token": token, "email": email, "password": password})
    if status == 200 and payload.get("ok"):
        print(f"Platform admin created: {email}. Sign in at "
              f"{base_url()}/login", file=out)
        return
    detail = payload.get("detail")
    code = detail.get("error") if isinstance(detail, dict) else detail
    if code == "already_bootstrapped":
        raise LocalError("This install already has an account — sign in at "
                         f"{base_url()}/login instead.")
    if code == "email_exists":
        raise LocalError("An account with that email already exists — use "
                         "another email, or sign in as that account.")
    raise LocalError(f"Bootstrap failed (HTTP {status}): {code}")
