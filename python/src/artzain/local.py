def manifest_source(explicit: str | None = None) -> str:
    """Precedence: --manifest flag, COGNEXUS_CHANNEL_MANIFEST, the default."""
    return (
        (explicit or "").strip()
        or (os.environ.get("COGNEXUS_CHANNEL_MANIFEST") or "").strip()
        or DEFAULT_MANIFEST_URL
    )


def load_manifest(source: str) -> dict[str, Any]:
    """Fetch and validate a stable-channel manifest (URL or local file)."""
    if source.startswith(("http://", "https://")):
        req = urllib.request.Request(
            source, headers={"Accept": "application/json",
                             "User-Agent": "artzain-local"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                raw = resp.read().decode("utf-8")
        except (urllib.error.URLError, OSError) as exc:
            raise LocalError(
                f"Could not fetch the channel manifest from {source} ({exc}). "
                "Pass --manifest <url-or-file> (e.g. the stable.json artifact "
                "from the release run) or set COGNEXUS_CHANNEL_MANIFEST."
            ) from exc
    else:
        path = Path(source)
        if not path.is_file():
            raise LocalError(
                f"Manifest file not found: {path}. Pass --manifest with the "
                "path to a stable.json.")
        raw = path.read_text(encoding="utf-8")

    try:
        manifest = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise LocalError(
            f"The manifest at {source} is not valid JSON — expected the "
            "stable.json the release workflow publishes.") from exc
    return validate_manifest(manifest, source)


def validate_manifest(manifest: Any, source: str = "<manifest>") -> dict[str, Any]:
    if not isinstance(manifest, dict):
        raise LocalError(f"The manifest at {source} is not a JSON object.")
    registry = str(manifest.get("registry") or "").strip().rstrip("/")
    version = str(manifest.get("version") or "").strip()
    images = manifest.get("images")
    if not registry or not version or not isinstance(images, dict):
        raise LocalError(
            f"The manifest at {source} is missing registry/version/images — "
            "it does not look like a stable-channel manifest.")
    for name in _REQUIRED_IMAGES:
        entry = images.get(name)
        digest = str((entry or {}).get("digest") or "")
        if not _DIGEST_RE.match(digest):
            raise LocalError(
                f"The manifest at {source} has no sha256 digest for {name} — "
                "refusing to install from an unpinned manifest.")
    return manifest


def image_refs(manifest: dict[str, Any]) -> dict[str, str]:
    """``repo -> registry/repo@sha256:...`` — digests only, never tags."""
    registry = str(manifest["registry"]).rstrip("/")
    return {
        name: f"{registry}/{name}@{manifest['images'][name]['digest']}"
        for name in _REQUIRED_IMAGES
    }


