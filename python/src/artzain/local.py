def _compose_cmd(args: list[str]) -> list[str]:
    return ["docker", "compose", "-f", str(_compose_path()),
            "--env-file", str(_env_path()), "-p", _PROJECT, *args]


def _compose(args: list[str], check: bool = True,
             timeout: int = 900) -> subprocess.CompletedProcess:
    try:
        proc = subprocess.run(_compose_cmd(args), capture_output=True,
                              text=True, timeout=timeout)
    except FileNotFoundError as exc:
        raise LocalError("docker is not installed — run `artzain local "
                         "doctor` for the fix.") from exc
    except subprocess.TimeoutExpired as exc:
        raise LocalError(f"`docker compose {args[0]}` timed out after "
                         f"{timeout}s.") from exc
    if check and proc.returncode != 0:
        tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-8:]
        raise LocalError(
            f"`docker compose {' '.join(args)}` failed:\n  " + "\n  ".join(tail))
    return proc


def _get_json(path: str, timeout: float = 5.0) -> dict[str, Any] | None:
    """GET a local engine endpoint; ``None`` means unreachable/not JSON —
    an answer, not an error, on a stack that may simply not be up yet."""
    try:
        with urllib.request.urlopen(f"{base_url()}{path}",
                                    timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception:  # noqa: BLE001
        return None


def fetch_health(timeout: float = 5.0) -> dict[str, Any] | None:
    return _get_json("/health", timeout=timeout)


def wait_healthy(timeout_s: int = _HEALTH_TIMEOUT_S,
                 sleep: Callable[[float], None] | None = None,
                 log: Callable[[str], None] = lambda s: None) -> dict[str, Any]:
    import time

    sleep = sleep or time.sleep
    deadline = time.monotonic() + timeout_s
    last = "the engine to answer /health"
    while time.monotonic() < deadline:
        payload = fetch_health()
        if payload:
            status = payload.get("status")
            if status == "healthy":
                return payload
            last = f"status={status} (db={payload.get('db_connected')})"
        log(f"waiting on {last} ...")
        sleep(3)
    raise LocalError(
        f"The engine did not report healthy within {timeout_s}s (last: "
        f"{last}). `docker compose -p {_PROJECT} logs analyzer` shows why.")


def _api_post(path: str, body: dict[str, Any],
              timeout: float = 30.0) -> tuple[int, dict[str, Any]]:
    data = json.dumps(body).encode("utf-8")
    req = urllib.request.Request(
        f"{base_url()}{path}", data=data,
        headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        raw = exc.read().decode("utf-8", errors="replace")
        try:
            return exc.code, json.loads(raw)
        except json.JSONDecodeError:
            # A gateway's HTML error page is still the only diagnostic the
            # caller has — keep it, don't flatten it to {}.
            return exc.code, {"detail": raw[:300]}
    except (urllib.error.URLError, OSError) as exc:
        raise LocalError(f"Could not reach the engine at {base_url()}: "
                         f"{exc}") from exc


def login_session(email: str, password: str) -> str:
    """Email/password login against the LOCAL engine; returns the JWT.

    The activate flow's fallback for operators who never minted an API key
    — which, on an expired trial, they can no longer do.
    """
    status, payload = _api_post("/api/auth/login",
                                {"email": email, "password": password})
    if status == 200 and payload.get("mfa_required"):
        raise LocalError(
            "This account has two-factor enabled, which the CLI login cannot "
            "complete. Sign in on the dashboard and create an API key there "
            "(Account -> API keys), then set COGNEXUS_API_KEY and retry.")
    token = payload.get("token") if status == 200 else None
    if not token:
        detail = payload.get("detail")
        raise LocalError(f"Sign-in failed (HTTP {status}): "
                         f"{detail or 'invalid email or password'}")
    return str(token)


def bootstrap_state(retries: int = 3,
                    sleep: Callable[[float], None] | None = None) -> dict[str, Any]:
    """The /welcome pre-check, with the *reason* preserved.

    ``unreachable`` (transient) must never be mistaken for
    ``already_bootstrapped`` — that mistake sent fresh installs to a login
    page with zero accounts.
    """
    import time

    sleep = sleep or time.sleep
    for attempt in range(retries):
        state = _get_json("/api/auth/bootstrap-status", timeout=10)
        if isinstance(state, dict) and "available" in state:
            return state
        if attempt < retries - 1:
            sleep(2)
    return {"available": False, "reason": "unreachable"}


def first_run_plan() -> tuple[str, str]:
    """``(url, note)`` for the end of ``up`` — a pure decision, testable.

    * available            -> the one-time /welcome URL.
    * already_bootstrapped -> /login.
    * disabled             -> /login, with a note (no token configured).
    * unreachable/unavailable -> STILL the /welcome URL (the page guards
      itself), plus an honest note and the headless fallback.
    """
    token = read_env().get("COGNEXUS_BOOTSTRAP_TOKEN") or ""
    state = bootstrap_state()
    reason = state.get("reason")
    welcome = f"{base_url()}/welcome?token={token}" if token else ""
    if state.get("available") and welcome:
        return welcome, "The account you create there is the platform admin."
    if reason == "already_bootstrapped" or not welcome:
        return f"{base_url()}/login", "This install already has an account."
    if reason == "disabled":
        return (f"{base_url()}/login",
                "Bootstrap is disabled on this deployment (no token "
                "configured server-side).")
    return (welcome,
            "The first-run status probe did not answer; if that page says "
            "the install is already set up, sign in at /login instead — or "
            "run `artzain local create-admin --email you@example.com`.")


