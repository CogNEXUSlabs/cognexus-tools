def _run(cmd: list[str], timeout: int = 30) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)


def _port_free(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        # No SO_REUSEADDR: on Windows it lets the bind SUCCEED against a
        # port that is actively in use, making this check pass exactly when
        # it should fail. SO_EXCLUSIVEADDRUSE (Windows-only) asks for the
        # strict semantics explicitly.
        if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
            s.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        try:
            s.bind(("127.0.0.1", port))
            return True
        except OSError:
            return False


def _arch() -> str:
    import platform

    machine = platform.machine().lower()
    if machine in ("x86_64", "amd64"):
        return "amd64"
    if machine in ("arm64", "aarch64"):
        return "arm64"
    return machine


def doctor_checks(port: int | None = None) -> list[tuple[str, bool, str]]:
    """``(name, ok, remedy)`` triples; remedy is one actionable sentence."""
    checks: list[tuple[str, bool, str]] = []
    port = port or ui_port()

    docker = shutil.which("docker") is not None
    checks.append((
        "docker installed", docker,
        "Install Docker Desktop (or Docker Engine + the compose plugin) from "
        "docs.docker.com/get-docker and re-run.",
    ))

    if docker:
        try:
            daemon = _run(["docker", "info", "--format", "{{.ServerVersion}}"]).returncode == 0
        except (OSError, subprocess.TimeoutExpired):
            daemon = False
        checks.append((
            "docker daemon running", daemon,
            "Start Docker Desktop (or `systemctl start docker`) and wait for "
            "it to report running.",
        ))
        try:
            compose_v2 = _run(["docker", "compose", "version"]).returncode == 0
        except (OSError, subprocess.TimeoutExpired):
            compose_v2 = False
        checks.append((
            "docker compose v2", compose_v2,
            "Update Docker Desktop, or install the compose plugin "
            "(docs.docker.com/compose/install).",
        ))

    arch = _arch()
    checks.append((
        f"cpu architecture ({arch})", arch in ("amd64", "arm64"),
        "Published images cover amd64 and arm64 only — run on an x86-64 or "
        "ARM64 host.",
    ))

    running = _stack_running()
    port_ok = _port_free(port) or running
    checks.append((
        f"port {port} available", port_ok,
        f"Something else is listening on {port} — stop it, or re-run with "
        f"`artzain local up --port <port>` (stored in {_env_path()}).",
    ))

    try:
        free = shutil.disk_usage(str(workspace_dir().parent)).free
    except OSError:
        free = _MIN_FREE_BYTES
    checks.append((
        "free disk (>= 2 GB)", free >= _MIN_FREE_BYTES,
        "Free some disk space — the images and database need about 2 GB.",
    ))
    return checks


def _stack_running() -> bool:
    if not _compose_path().is_file():
        return False
    try:
        out = _compose(["ps", "--quiet"], check=False)
        return bool(out.stdout.strip())
    except LocalError:
        return False


